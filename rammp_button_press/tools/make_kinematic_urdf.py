"""Regenerate urdf/gen3_tool_frame_kinematic.urdf from the repo's Gen3 URDF.

Keeps the arm chain world -> base_link -> ... -> end_effector_link -> tool_frame (the link the
button press has always planned in; it is Kinova's tool frame, flange + 0.120 m along z) and
drops every visual / collision mesh and the gripper, so PyBullet can load it without meshes.
The kinematics are copied verbatim -- test/test_kinematics.py checks FK against the full sim.

    python3 rammp_button_press/tools/make_kinematic_urdf.py   # from the feeding-deployment root
"""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src/feeding_deployment/assets/robot/robot.urdf"
DST = Path(__file__).resolve().parents[1] / "urdf/gen3_tool_frame_kinematic.urdf"
KEEP_LINKS = ["world", "base_link", "shoulder_link", "half_arm_1_link", "half_arm_2_link", "forearm_link",
              "spherical_wrist_1_link", "spherical_wrist_2_link", "bracelet_link", "end_effector_link", "tool_frame"]


def main() -> int:
    src = ET.parse(SRC).getroot()
    out = ET.Element("robot", name="gen3_tool_frame_kinematic")
    out.append(ET.Comment(f" GENERATED by rammp_button_press/tools/make_kinematic_urdf.py from {SRC.relative_to(ROOT)} "
                          "-- arm chain to tool_frame, no meshes. Do not edit by hand. "))
    for el in src:
        if el.tag == "link" and el.get("name") in KEEP_LINKS:
            link = ET.SubElement(out, "link", name=el.get("name"))
            if (inertial := el.find("inertial")) is not None:
                link.append(inertial)
        elif el.tag == "joint" and el.find("child").get("link") in KEEP_LINKS and el.find("parent").get("link") in KEEP_LINKS:
            out.append(el)
    ET.indent(out)
    DST.write_text('<?xml version="1.0" ?>\n' + ET.tostring(out, encoding="unicode") + "\n")
    print(f"wrote {DST}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
